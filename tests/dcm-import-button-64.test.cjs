'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('tim-pusmantap-mt.html','utf8');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
const script=scripts.map(x=>x[1]).find(x=>x.includes("mt-import-profiles"));
assert(script,'Click handler script must exist');
let onClick,openCount=0,toastText='',ready=false;
const errorBox={hidden:true,textContent:''};
const button={addEventListener(name,fn,capture){assert.equal(name,'click');assert.equal(capture,true);onClick=fn}};
const document={getElementById(id){return id==='mt-import-profiles'?button:id==='mt-error'?errorBox:null}};
const window={mtTeamReady(){ready=true},MT_PROFILE_IMPORT:{open(){openCount++}},toast(s){toastText=s}};
vm.runInNewContext(script,{document,window,console});
assert(ready,'Host must initialize MT');
assert.equal(typeof onClick,'function');
let stopped=false;
onClick({preventDefault(){},stopImmediatePropagation(){stopped=true}});
assert(stopped,'Click must not reach MT delegated handlers');
assert.equal(openCount,1,'Import dialog must open exactly once');
window.MT_PROFILE_IMPORT.open=()=>{throw Error('Test: popup unavailable')};
onClick({preventDefault(){},stopImmediatePropagation(){}});
assert.match(errorBox.textContent,/popup unavailable/);
assert.equal(errorBox.hidden,false);
assert.match(toastText,/popup unavailable/);
const compare=fs.readFileSync('mt-team-exact/dcm-profile-compare-50.js','utf8');
assert(compare.includes("wrap.style.cssText='position:fixed!important"),'Dialog needs a visible CSS fallback');
assert(compare.includes('hostDocument.body.appendChild(wrap)'),'Dialog must appear in parent viewport');
assert(compare.includes('id="cmp-file" type="file"'),'Native picker must not depend on iframe listeners');
console.log('PASS: Import Profil & Foto click, error feedback and modal wiring.');